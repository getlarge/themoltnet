/**
 * Runtime locks for GitHub Actions released by release-please.
 *
 * release-please bumps a component only for commits under its package path,
 * but consumers pinned to an action's major tag may also run files outside
 * that package at the tag's commit, such as a reusable workflow. The lock
 * file inside the package records a hash of each of those files, so a
 * change to one must update the lock, which touches the package and cuts a
 * release. Bundles are not committed, so they are not locked: the release
 * job builds them into the commit the stable major tag points at.
 *
 * Plain Node (erasable TypeScript, built-ins only), so CI runs it without an
 * install: `node tools/src/release/action-runtime-lock.ts --check|--write`.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export interface RuntimeLock {
  /** Lock file, relative to the repository root. */
  lock: string;
  /** Git pathspecs of the files the action runs from outside its package. */
  pathspecs: string[];
}

/** One entry per released action that runs files from outside its package. */
export const RUNTIME_LOCKS: RuntimeLock[] = [
  {
    // The reusable workflows and their scripts run from the tag's commit,
    // and the bundle inlines the review libraries. Other bundled workspace
    // libraries reach the tag at the action's next release.
    lock: 'packages/adaptive-review-action/runtime.lock',
    pathspecs: [
      '.github/workflows/adaptive-review-reusable.yml',
      '.github/workflows/adaptive-review-outcomes-reusable.yml',
      'tools/adaptive-review-action-digest.sh',
      'tools/fetch-adaptive-review-head.sh',
      'libs/adaptive-review/src',
      'libs/complexity-review/src',
      'libs/docs-impact-review/src',
      'libs/security-review/src',
      ':(exclude,glob)**/*.test.ts',
      ':(exclude,glob)**/*.spec.ts',
    ],
  },
];

const HEADER = [
  '# Generated by tools/src/release/action-runtime-lock.ts --write.',
  '# Files this action runs from outside its package; a change here must',
  '# ship as a fix or feat commit so release-please releases the action.',
];

/** The lock text for `files` (path → content), sorted by path. */
export function renderLock(files: ReadonlyMap<string, Buffer>): string {
  const lines = [...files.keys()].sort().map((path) => {
    const content = files.get(path) ?? Buffer.alloc(0);
    return `${createHash('sha256').update(content).digest('hex')}  ${path}`;
  });
  return `${[...HEADER, ...lines].join('\n')}\n`;
}

function listFiles(root: string, pathspecs: string[]): string[] {
  return execFileSync(
    'git',
    // Staged files only, NUL-separated: an untracked local file never enters
    // the lock, and no path is quoted.
    ['ls-files', '--cached', '-z', '--', ...pathspecs],
    { cwd: root, encoding: 'utf8' },
  )
    .split('\0')
    .filter(Boolean);
}

export function computeLock(root: string, spec: RuntimeLock): string {
  const files = new Map<string, Buffer>();
  for (const path of listFiles(root, spec.pathspecs)) {
    files.set(path, readFileSync(join(root, path)));
  }
  return renderLock(files);
}

/** The locks that belong to the action project at `projectRoot`. */
export function locksForProject(
  projectRoot: string,
  locks = RUNTIME_LOCKS,
): RuntimeLock[] {
  const prefix = `${projectRoot.replace(/\/+$/, '')}/`;
  return locks.filter((lock) => lock.lock.startsWith(prefix));
}

/** Locks whose committed text differs from the files they cover. */
export function staleLocks(root: string, locks = RUNTIME_LOCKS): string[] {
  return locks
    .filter((spec) => {
      let current = '';
      try {
        current = readFileSync(join(root, spec.lock), 'utf8');
      } catch {
        return true;
      }
      return current !== computeLock(root, spec);
    })
    .map((spec) => spec.lock);
}

function main(argv: string[]): number {
  const root = execFileSync('git', ['rev-parse', '--show-toplevel'], {
    encoding: 'utf8',
  }).trim();
  if (argv.includes('--write')) {
    for (const spec of RUNTIME_LOCKS) {
      writeFileSync(join(root, spec.lock), computeLock(root, spec));
    }
    return 0;
  }
  if (argv.includes('--check')) {
    const stale = staleLocks(root);
    for (const lock of stale) {
      process.stderr.write(
        `::error file=${lock}::${lock} is out of date. Stage your changes, run 'node tools/src/release/action-runtime-lock.ts --write', and commit the lock in a fix or feat commit, so the action is released with the change.\n`,
      );
    }
    return stale.length > 0 ? 1 : 0;
  }
  process.stderr.write(
    'Usage: node tools/src/release/action-runtime-lock.ts --check|--write\n',
  );
  return 2;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  process.exitCode = main(process.argv.slice(2));
}
