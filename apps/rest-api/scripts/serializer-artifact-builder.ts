import {
  type Serializer,
  type SerializerFactory,
  StandaloneSerializer,
} from '@fastify/fast-json-stringify-compiler';

import {
  serializerSchemaKey,
  serializerScopeKey,
} from '../src/serializer-artifact.js';

/** Collect the upstream-generated serializers while Fastify registers routes. */
export function createSerializerArtifactBuilder(): {
  factory: SerializerFactory;
  source: () => string;
} {
  const scopes = new Map<string, Map<string, string>>();
  const factory: SerializerFactory = (schemas, options) => {
    const scopeKey = serializerScopeKey(schemas, options);
    const scope = scopes.get(scopeKey) ?? new Map<string, string>();
    scopes.set(scopeKey, scope);
    const compiled = new Map<string, Serializer>();

    return (route) => {
      const schemaKey = serializerSchemaKey(route.schema);
      const existing = compiled.get(schemaKey);
      if (existing) return existing;

      // Upstream mutates options and its $id reference map. Start each miss
      // with fresh compiler state so generation cannot change the next key.
      const serializer = StandaloneSerializer({
        readMode: false,
        storeFunction: (_route, source) => scope.set(schemaKey, source),
      })(schemas, { ...options })(route);
      compiled.set(schemaKey, serializer);
      return serializer;
    };
  };

  return { factory, source: () => renderArtifact(scopes) };
}

function renderArtifact(scopes: Map<string, Map<string, string>>): string {
  const entries = [...scopes].map(([scopeKey, serializers]) => {
    const modules = [...serializers].map(([schemaKey, source]) => {
      // Each upstream serializer writes module.exports. Give it a private
      // CommonJS module; `require` comes from the runtime compatibility adapter.
      return `${JSON.stringify(schemaKey)}: (() => {
        const module = { exports: {} };
        ${source}
        return module.exports;
      })()`;
    });
    return `${JSON.stringify(scopeKey)}: { ${modules.join(',\n')} }`;
  });

  return `'use strict';
// Generated by scripts/generate-openapi.ts. Do not edit.
module.exports = {
  version: 2,
  createScopes(require) {
    return { ${entries.join(',\n')} };
  }
};
`;
}
